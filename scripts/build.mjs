// Spytrix build: src/ -> dist/ (override with SPYTRIX_OUT). SPYTRIX_CA overrides the registry CA record.
import fs from 'node:fs';
import path from 'node:path';
const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.resolve(ROOT, process.env.SPYTRIX_OUT || 'dist');
if (!OUT.startsWith(ROOT + path.sep)) throw new Error('refusing to write outside project: ' + OUT);

const B58 = /^[1-9A-HJ-NP-Za-km-z]{32,44}$/;
const reg = JSON.parse(fs.readFileSync(path.join(SRC, 'registry.json'), 'utf8'));
if (process.env.SPYTRIX_CA) reg.ca = { state: 'stated', value: process.env.SPYTRIX_CA.trim() };
if (reg.ca.state === 'stated' && !B58.test(reg.ca.value || '')) throw new Error('CA is stated but not a base58 mint address');
for (const k of ['x', 'github']) if (reg[k].state !== 'stated') reg[k].url = null;
if (reg.ca.state !== 'stated') reg.ca.value = null;
const handle = u => { try { return '@' + new URL(u).pathname.split('/').filter(Boolean)[0]; } catch { return null; } };

const ICON_X = '<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M18.244 2.25h3.308l-7.227 8.26 8.502 11.24H16.17l-5.214-6.817L4.99 21.75H1.68l7.73-8.835L1.254 2.25H8.08l4.713 6.231zm-1.161 17.52h1.833L7.084 4.126H5.117z"/></svg>';
const ICON_GH = '<svg viewBox="0 0 16 16" fill="currentColor" aria-hidden="true"><path d="M8 0c4.42 0 8 3.58 8 8a8.013 8.013 0 0 1-5.45 7.59c-.4.08-.55-.17-.55-.38 0-.27.01-1.13.01-2.2 0-.75-.25-1.23-.54-1.48 1.78-.2 3.65-.88 3.65-3.95 0-.88-.31-1.59-.82-2.15.08-.2.36-1.02-.08-2.12 0 0-.67-.22-2.2.82-.64-.18-1.32-.27-2-.27-.68 0-1.36.09-2 .27-1.53-1.03-2.2-.82-2.2-.82-.44 1.1-.16 1.92-.08 2.12-.51.56-.82 1.28-.82 2.15 0 3.06 1.86 3.75 3.64 3.95-.23.2-.44.55-.51 1.07-.46.21-1.61.55-2.33-.66-.15-.24-.6-.83-1.23-.82-.67.01-.27.38.01.53.34.19.73.9.82 1.13.16.45.68 1.31 2.69.94 0 .67.01 1.3.01 1.49 0 .21-.15.45-.55.38A7.995 7.995 0 0 1 0 8c0-4.42 3.58-8 8-8Z"/></svg>';

// LINK RULE: href only for stated records; handle derived from the stored URL.
const icon = (rec, svg, name) => rec.state === 'stated'
  ? `<a class="icon-link" data-social="${name}" href="${rec.url}" target="_blank" rel="noopener noreferrer" aria-label="${name === 'x' ? 'X (' + handle(rec.url) + ')' : 'GitHub'}">${svg}</a>`
  : `<span class="icon-link is-inert" data-social="${name}" role="img" aria-disabled="true" aria-label="${name === 'x' ? 'X (not available)' : 'GitHub (not available yet)'}">${svg}</span>`;
const socials = '        ' + icon(reg.x, ICON_X, 'x') + '\n        ' + icon(reg.github, ICON_GH, 'github');
const footerX = reg.x.state === 'stated'
  ? `<a data-social="x" href="${reg.x.url}" target="_blank" rel="noopener noreferrer">X (${handle(reg.x.url)})</a>` : '<span class="inert" data-social="x" aria-disabled="true">X</span>';
const footerGh = reg.github.state === 'stated'
  ? `<a data-social="github" href="${reg.github.url}" target="_blank" rel="noopener noreferrer">GitHub</a>` : '<span class="inert" data-social="github" aria-disabled="true">GitHub</span>';
const ctaX = reg.x.state === 'stated'
  ? `<a class="btn btn-amber" data-social="x" href="${reg.x.url}" target="_blank" rel="noopener noreferrer">Follow ${handle(reg.x.url)} &rarr;</a>` : '';

const stated = reg.ca.state === 'stated';
const ca = `  <div class="ca-bar" id="caBar" data-state="${reg.ca.state}">
    <div class="wrap ca-inner">
      <div class="ca-meta">
        <div class="ca-kicker"><span>Contract address</span><span class="chain-chip">MAINNET</span></div>
        ${stated
          ? `<button type="button" class="ca-addr" id="caAddr" aria-label="Copy contract address">${reg.ca.value}</button>`
          : `<div class="ca-addr" id="caAddr">Not announced yet<span class="ca-caret" aria-hidden="true"></span></div>`}
      </div>
      <button type="button" class="btn btn-sm ca-copy" id="caCopy"${stated ? '' : ' disabled aria-disabled="true"'}>${stated ? 'Copy' : 'Pending'}</button>
    </div>
  </div>`;

// ---- assemble output
fs.rmSync(OUT, { recursive: true, force: true });
for (const d of ['assets/css', 'assets/js', 'assets/img']) fs.mkdirSync(path.join(OUT, d), { recursive: true });
for (const d of ['css', 'js']) for (const f of fs.readdirSync(path.join(SRC, 'assets', d))) fs.copyFileSync(path.join(SRC, 'assets', d, f), path.join(OUT, 'assets', d, f));
// explicit copies of brand-derived images (the logo is mandatory in the built site)
for (const f of ['logo-512.png', 'logo-128.png', 'favicon.svg', 'banner.jpg']) {
  const s = path.join(SRC, 'assets/img', f);
  if (!fs.existsSync(s)) throw new Error('missing asset ' + f + ' - run npm run prep');
  fs.copyFileSync(s, path.join(OUT, 'assets/img', f));
}
fs.writeFileSync(path.join(OUT, 'assets/js/registry.js'), '// generated by scripts/build.mjs from src/registry.json\nexport const REGISTRY = ' + JSON.stringify(reg, null, 2) + ';\n');

const html = fs.readFileSync(path.join(SRC, 'index.html'), 'utf8')
  .replace('<!--@socials-->', socials).replace('<!--@ca-->', ca)
  .replace('<!--@cta-x-->', ctaX ? '          ' + ctaX : '')
  .replace('<!--@footer-social-->', '          ' + footerX + '\n          ' + footerGh);
fs.writeFileSync(path.join(OUT, 'index.html'), html);

// logo gate: file present in output and referenced by the right relative path
if (!fs.existsSync(path.join(OUT, 'assets/img/logo-512.png'))) throw new Error('logo missing from output');
for (const ref of ['assets/img/logo-128.png', 'assets/img/logo-512.png', 'assets/img/favicon.svg'])
  if (!html.includes(ref)) throw new Error('index.html does not reference ' + ref);
console.log(`build ok -> ${path.relative(ROOT, OUT)}  (CA ${reg.ca.state})`);
